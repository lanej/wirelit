import { fromJson, toJson, type DescEnum, type DescField, type DescMessage, type DescMethod, type DescService, type JsonValue } from '@bufbuild/protobuf';
import type { SchemaModel } from './schema.js';
import { symbolId, symbolPath } from './schema.js';
import { attribute, cell, fence, literal, markdown } from './markdown.js';
import { examplesFor } from './snippets.js';
import type { GenerateOptions, MethodExample } from './types.js';
import { wktJson } from './well-known.js';

const scalarNames: Record<number, string> = { 1: 'double', 2: 'float', 3: 'int64', 4: 'uint64', 5: 'int32', 6: 'fixed64', 7: 'fixed32', 8: 'bool', 9: 'string', 12: 'bytes', 13: 'uint32', 15: 'sfixed32', 16: 'sfixed64', 17: 'sint32', 18: 'sint64' };
const longTypes = new Set([3, 4, 6, 16, 18]);
const shapeNames = { unary: 'Unary', server_streaming: 'Server streaming', client_streaming: 'Client streaming', bidi_streaming: 'Bidirectional streaming' };

export interface Rendered { pages: Map<string, string>; warnings: string[] }

export function render(model: SchemaModel, config: GenerateOptions): Rendered {
  const pages = new Map<string, string>();
  const routes = new Set<string>();
  const segments = config.mount.split('/').filter(Boolean);
  const root = '/' + segments.join('/') + (segments.length ? '/' : '');
  const href = (s: DescService | DescMethod | DescMessage | DescEnum) => `${root}${symbolPath(s)}/`;
  const link = (s: DescService | DescMethod | DescMessage | DescEnum) => `[${s.name}](${href(s)})`;
  const metadata = `Source: ${literal(config.sourceVersion ?? 'unspecified')} · Generator: ${literal('Wirelit 0.1.0')}`;
  const warnings = [...model.warnings];
  const knownMethods = new Set(model.services.flatMap(s => s.methods.map(symbolId)));
  for (const id of Object.keys(config.examples ?? {})) if (!knownMethods.has(id)) throw new Error(`Example refers to an unselected or unknown method: ${id}`);
  function add(path: string, title: string, content: string, order?: number) {
    if (routes.has(path.toLowerCase())) throw new Error(`Generated route collision: ${path}`);
    routes.add(path.toLowerCase());
    const frontmatter = `---\ntitle: ${JSON.stringify(title)}\ndescription: ${JSON.stringify(`Connect API reference for ${title}`)}\neditUrl: false\n${order === undefined ? '' : `sidebar:\n  order: ${order}\n`}---`;
    pages.set(`${path}.mdx`, `${frontmatter}\n\n{/* Generated by Wirelit. Edit the schema or example sources. */}\n\n${content.trim()}\n\n---\n\n${metadata}\n`);
  }
  function description(s: Parameters<SchemaModel['comment']>[0]) {
    return [s.deprecated ? '**Deprecated.**\n' : '', markdown(model.comment(s))].filter(Boolean).join('\n');
  }
  function canonical(type: DescMessage, value: JsonValue, context: string): JsonValue {
    try { return toJson(type, fromJson(type, value, { registry: model.registry }), { registry: model.registry }); }
    catch (e) { throw new Error(`Invalid ${context}: ${e instanceof Error ? e.message : String(e)}`); }
  }
  function normalizedExample(m: DescMethod): MethodExample | undefined {
    const input = config.examples?.[symbolId(m)];
    if (!input) return;
    if (m.proto.clientStreaming && input.request !== undefined) throw new Error(`Use a streaming client example for ${symbolId(m)}; a single request is misleading.`);
    if (m.proto.serverStreaming && input.response !== undefined) throw new Error(`Use responses, not response, for streaming method ${symbolId(m)}.`);
    if (!m.proto.serverStreaming && input.responses !== undefined) throw new Error(`Use response, not responses, for unary response method ${symbolId(m)}.`);
    return {
      ...input,
      request: input.request === undefined ? undefined : canonical(m.input, input.request, `${symbolId(m)} request`),
      response: input.response === undefined ? undefined : canonical(m.output, input.response, `${symbolId(m)} response`),
      responses: input.responses?.map(v => canonical(m.output, v, `${symbolId(m)} stream response`)),
    };
  }
  add('index', config.title ?? 'API reference', `The Connect API contract, generated from Protobuf.\n\n## Services\n\n${model.services.map(s => `- ${link(s)} — ${cell(markdown(model.comment(s).split('\n')[0] ?? ''))}`).join('\n')}\n\n## Message and enum types\n\n${model.types.map(t => `- ${link(t)} — ${literal(t.typeName)}`).join('\n')}`, 0);
  for (const service of model.services) {
    add(symbolPath(service), service.name, `${literal(service.typeName)}\n\n${description(service)}\n\n## Methods\n\n| Method | Shape | Request | Response |\n| --- | --- | --- | --- |\n${service.methods.map(m => `| ${link(m)} | ${shapeNames[m.methodKind]} | ${link(m.input)} | ${link(m.output)} |`).join('\n')}`);
    for (const method of service.methods) {
      const example = normalizedExample(method);
      const snippets = examplesFor(method, example?.request, config);
      // Linked types are part of the signature, rather than repeated below it.
      // Semantic HTML works in MDX without a custom runtime or highlighter plugin.
      const typeLink = (type: DescMessage) => `<a href="${attribute(href(type))}" title="${attribute(type.typeName)}">${type.name}</a>`;
      const keyword = (word: string) => `<strong>${word}</strong>`;
      const signature = `<pre className="wirelit-signature"><code>${keyword('rpc')} <span>${method.name}</span>(${method.proto.clientStreaming ? keyword('stream') + ' ' : ''}${typeLink(method.input)}) ${keyword('returns')} (${method.proto.serverStreaming ? keyword('stream') + ' ' : ''}${typeLink(method.output)});</code></pre>`;
      const url = `${config.baseUrl.replace(/\/$/, '')}/${service.typeName}/${method.name}`;
      const streaming = method.methodKind !== 'unary';
      let content = `${link(service)} · **${shapeNames[method.methodKind]}**\n\n${description(method)}\n\n## RPC contract\n\n${signature}\n\n## Connect endpoint\n\n${fence(`POST ${url}`, 'http')}\n\n${streaming ? 'Content types: `application/connect+json` or `application/connect+proto`. Messages use Connect stream envelopes. End-of-stream errors and metadata are carried in the final envelope.' : 'Content types: `application/json` or `application/proto`. The unary body is one message.'}\n\n${method.idempotency === 1 ? '**No side effects** is declared in the schema. GET availability depends on the deployed server configuration.' : method.idempotency === 2 ? '**Idempotent** is declared in the schema.' : 'The schema declares no idempotency guarantee.'}`;
      if (config.protocolGuide) content += `\n\nSee [protocol behavior](${config.protocolGuide}) for metadata, deadlines, errors, cancellation, and streaming.`;
      if (example?.notes) content += `\n\n${markdown(example.notes)}`;
      if (example?.request !== undefined) content += `\n\n## Request example\n\n${fence(JSON.stringify(example.request, null, 2), 'json')}`;
      if (snippets.length) {
        content = `import { Tabs, TabItem } from '@astrojs/starlight/components';\n\n${content}\n\n## Calling this method\n\n<Tabs>\n${snippets.map(s => `<TabItem label=${JSON.stringify(s.label)}>\n\n${fence(s.code, s.language)}\n\n</TabItem>`).join('\n')}\n</Tabs>`;
      } else {
        warnings.push(`No executable request example for ${symbolId(method)}.`);
        content += '\n\n## Examples\n\nA runnable client example has not been supplied for this method. The RPC signature and linked message contracts remain available.';
      }
      if (example?.response !== undefined) content += `\n\n## Response example\n\n${fence(JSON.stringify(example.response, null, 2), 'json')}`;
      if (example?.responses) content += `\n\n## Streamed messages\n\nThese are individual decoded messages. The SDK handles framing and end-of-stream metadata.\n\n${example.responses.map(v => fence(JSON.stringify(v, null, 2), 'json')).join('\n\n')}`;
      if (example?.errors?.length) content += `\n\n## Documented errors\n\n${example.errors.map(e => `### ${e.code}\n\n${markdown(e.message)}`).join('\n\n')}`;
      add(symbolPath(method), method.name, content);
    }
  }
  for (const type of model.types) {
    let content = `${literal(type.typeName)}\n\n${Object.hasOwn(wktJson, type.typeName) ? '' : description(type)}`;
    if (type.kind === 'enum') {
      content += `\n\n## Values\n\n| Name | Number | Description |\n| --- | --- | --- |\n${type.values.map(v => `| ${literal(v.name)} | ${v.number} | ${cell(description(v))} |`).join('\n')}\n\nProtoJSON serializers normally emit enum names. Parsers also accept integer enum values.`;
    } else if (Object.hasOwn(wktJson, type.typeName)) {
      content += `\n\n## JSON representation\n\n${wktJson[type.typeName] ?? 'See the Protobuf well-known type specification.'}\n\nSee the [ProtoJSON format](https://protobuf.dev/programming-guides/json/) for the complete encoding rules.`;
    } else {
      content += '\n\n## Fields\n\nField presence and validation are separate properties. Implicit scalar defaults are normally omitted in ProtoJSON.\n';
      for (const field of type.fields) {
        content += `\n### ${field.name}\n\n${description(field)}\n\n| Property | Value |\n| --- | --- |\n| Protobuf name | ${literal(field.name)} |\n| JSON name | ${literal(field.jsonName)} |\n| Field number | ${field.number} |\n| Protobuf type | ${fieldType(field, link)} |\n| JSON representation | ${fieldJson(field)} |\n| Presence | ${presence(field)} |\n`;
        const rules = model.rules(field);
        if (rules !== undefined) content += `\n**Protovalidate rules**\n\nThese are declared validation constraints. JSON serialization does not enforce them.\n\n${fence(JSON.stringify(rules, null, 2), 'json')}\n`;
      }
    }
    add(symbolPath(type), type.name, content);
  }
  return { pages, warnings };
}

function fieldType(field: DescField, link: (s: DescMessage | DescEnum) => string): string {
  const value = field.message ? link(field.message) : field.enum ? link(field.enum) : literal(scalarNames[field.scalar ?? 0] ?? 'unknown');
  if (field.fieldKind === 'map') return `map of ${literal(scalarNames[field.mapKey] ?? 'string')} to ${value}`;
  return field.fieldKind === 'list' ? `repeated ${value}` : value;
}

function fieldJson(field: DescField): string {
  let value = field.message ? (wktJson[field.message.typeName] ?? 'Object')
    : field.enum ? 'Enum name (string)'
    : longTypes.has(field.scalar ?? 0) ? 'Decimal string'
    : field.scalar === 12 ? 'Base64 string' : field.scalar === 9 ? 'String' : field.scalar === 8 ? 'Boolean' : 'Number';
  if (field.fieldKind === 'map') value = `Object with string keys and ${value.toLowerCase()} values`;
  if (field.fieldKind === 'list') value = `Array of ${value.toLowerCase()} values`;
  return value;
}

function presence(field: DescField): string {
  if (field.oneof) return `Explicit; member of oneof ${literal(field.oneof.name)}`;
  if (field.fieldKind === 'list' || field.fieldKind === 'map') return 'Collection; empty and absent are not distinguished';
  return field.presence === 2 ? 'Implicit; default and absent are not distinguished' : field.presence === 3 ? 'Required by the Protobuf schema' : 'Explicit; absent is distinct from the default';
}
